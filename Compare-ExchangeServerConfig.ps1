function Invoke-AreaVirtualDirectories {
    $areaName = 'VirtualDirectories'
    $directoryTypes = @(
        @{ Get = 'Get-OwaVirtualDirectory';          Set = 'Set-OwaVirtualDirectory';          Exclude = @() },
        @{ Get = 'Get-EcpVirtualDirectory';          Set = 'Set-EcpVirtualDirectory';          Exclude = @() },
        @{ Get = 'Get-WebServicesVirtualDirectory';  Set = 'Set-WebServicesVirtualDirectory';  Exclude = @() },
        @{ Get = 'Get-ActiveSyncVirtualDirectory';   Set = 'Set-ActiveSyncVirtualDirectory';   Exclude = @('ActiveSyncServer') },
        @{ Get = 'Get-OabVirtualDirectory';          Set = 'Set-OabVirtualDirectory';          Exclude = @() },
        @{ Get = 'Get-MapiVirtualDirectory';         Set = 'Set-MapiVirtualDirectory';         Exclude = @() },
        @{ Get = 'Get-PowerShellVirtualDirectory';   Set = 'Set-PowerShellVirtualDirectory';   Exclude = @() },
        @{ Get = 'Get-AutodiscoverVirtualDirectory'; Set = 'Set-AutodiscoverVirtualDirectory'; Exclude = @() }
    )
    foreach ($type in $directoryTypes) {
        try {
            $sourceDirectories = @(& $type.Get -Server $script:SourceShort -ErrorAction Stop)
            $targetDirectories = @(& $type.Get -Server $script:TargetShort -ErrorAction Stop)
        }
        catch { Add-Result -Area $areaName -Object $type.Get -Property '(read)' -Status Info -Message $_.Exception.Message; continue }
        foreach ($directory in $sourceDirectories) {
            $counterpart = Get-TargetCounterpart -SourceObject $directory -TargetObjects $targetDirectories
            if ($null -eq $counterpart) { Add-Result -Area $areaName -Object ([string]$directory.Name) -Property '(exists)' -SourceValue 'present' -Status SourceOnly; continue }
            Compare-ObjectSettings -Area $areaName -Object ([string]$directory.Name) -SourceObject $directory -TargetObject $counterpart -SetCmdlet $type.Set -Exclude $type.Exclude | Out-Null
        }
    }
}

