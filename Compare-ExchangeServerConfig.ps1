function Invoke-AreaPopImap {
    $areaName = 'PopImap'
    foreach ($protocol in @(
        @{ Get = 'Get-ImapSettings'; Set = 'Set-ImapSettings'; Label = 'ImapSettings'; Services = @('MSExchangeIMAP4', 'MSExchangeIMAP4BE') },
        @{ Get = 'Get-PopSettings';  Set = 'Set-PopSettings';  Label = 'PopSettings';  Services = @('MSExchangePOP3', 'MSExchangePOP3BE') })) {
        $source = & $protocol.Get -Server $script:SourceShort -ErrorAction Stop
        $target = & $protocol.Get -Server $script:TargetShort -ErrorAction Stop
        Compare-ObjectSettings -Area $areaName -Object $protocol.Label -SourceObject $source -TargetObject $target -SetCmdlet $protocol.Set `
            -Exclude $script:PathExclusions -BindingProperties @('SSLBindings', 'UnencryptedOrTLSBindings') | Out-Null
        foreach ($serviceName in $protocol.Services) {
            try {
                $sourceService = Get-CimInstance -ClassName Win32_Service -ComputerName $script:SourceFqdn -Filter ("Name='{0}'" -f $serviceName) -ErrorAction Stop
                $targetService = Get-CimInstance -ClassName Win32_Service -ComputerName $script:TargetFqdn -Filter ("Name='{0}'" -f $serviceName) -ErrorAction Stop
                $status = if ([string]$sourceService.StartMode -eq [string]$targetService.StartMode) { 'Equal' } else { 'Different' }
                Add-Result -Area $areaName -Object $serviceName -Property 'StartMode' -SourceValue $sourceService.StartMode -TargetValue $targetService.StartMode -Status $status
                $status = if ([string]$sourceService.State -eq [string]$targetService.State) { 'Equal' } else { 'Different' }
                Add-Result -Area $areaName -Object $serviceName -Property 'State' -SourceValue $sourceService.State -TargetValue $targetService.State -Status $status
            }
            catch { Add-Result -Area $areaName -Object $serviceName -Property 'StartMode' -Status Info -Message ('Service state not readable remotely: {0}' -f $_.Exception.Message) }
        }
    }
}

function Get-EventLogCategory {
    param([string] $Identity)
    $parts = $Identity -split '\\'
    if ($parts.Count -ge 3) { return (($parts | Select-Object -Skip 1) -join '\') }
    return $Identity
}

function Invoke-AreaEventLogLevels {
    $areaName = 'EventLogLevels'
    $sourceLevels = @{}
    foreach ($level in @(Get-EventLogLevel -Server $script:SourceShort -ErrorAction Stop)) { $sourceLevels[(Get-EventLogCategory -Identity ([string]$level.Identity))] = [string]$level.EventLevel }
    $targetLevels = @{}
    foreach ($level in @(Get-EventLogLevel -Server $script:TargetShort -ErrorAction Stop)) { $targetLevels[(Get-EventLogCategory -Identity ([string]$level.Identity))] = [string]$level.EventLevel }
    foreach ($category in ($sourceLevels.Keys | Sort-Object)) {
        $sourceValue = $sourceLevels[$category]
        $targetValue = $targetLevels[$category]
        if ($sourceValue -eq 'Lowest' -and ($null -eq $targetValue -or $targetValue -eq 'Lowest')) { continue }
        $status = if ($sourceValue -eq $targetValue) { 'Equal' } elseif ($null -eq $targetValue) { 'SourceOnly' } else { 'Different' }
        Add-Result -Area $areaName -Object $category -Property 'EventLevel' -SourceValue $sourceValue -TargetValue $targetValue -Status $status
    }
    foreach ($category in ($targetLevels.Keys | Sort-Object)) {
        if ($sourceLevels.ContainsKey($category) -or $targetLevels[$category] -eq 'Lowest') { continue }
        Add-Result -Area $areaName -Object $category -Property 'EventLevel' -TargetValue $targetLevels[$category] -Status TargetOnly
    }
}

function Invoke-AreaSettingOverrides {
    foreach ($override in @(Get-SettingOverride -ErrorAction Stop)) {
        $servers = Get-ValueList -Value (ConvertTo-SettableValue -Value $override.Server)
        if ($servers.Count -eq 0) { continue }
        $onSource = $servers -contains $script:SourceShort
        $onTarget = $servers -contains $script:TargetShort
        if (-not $onSource -and -not $onTarget) { continue }
        $status = if ($onSource -and $onTarget) { 'Equal' } elseif ($onSource) { 'SourceOnly' } else { 'TargetOnly' }
        Add-Result -Area 'SettingOverrides' -Object ([string]$override.Name) -Property 'Server' -SourceValue $(if ($onSource) { 'scoped' } else { '' }) -TargetValue $(if ($onTarget) { 'scoped' } else { '' }) -Status $status `
            -Message ((ConvertTo-SettableValue -Value $override.Parameters) -join '; ')
    }
}

function Get-AceKey {
    param($Ace)
    $user = Convert-ServerName -Value ([string]$Ace.User)
    return ('{0}|{1}|{2}|{3}' -f $user.ToLowerInvariant(), (Get-CompareKey (ConvertTo-SettableValue -Value $Ace.ExtendedRights)), (Get-CompareKey (ConvertTo-SettableValue -Value $Ace.AccessRights)), [bool]$Ace.Deny)
}

function Get-AceDescription {
    param($Ace)
    $rights = @(Get-ValueList -Value (ConvertTo-SettableValue -Value $Ace.ExtendedRights)) + @(Get-ValueList -Value (ConvertTo-SettableValue -Value $Ace.AccessRights))
    return ('{0}: {1}{2}' -f (Convert-ServerName -Value ([string]$Ace.User)), (($rights | Where-Object { $_ -and $_ -ne 'ExtendedRight' }) -join ','), $(if ([bool]$Ace.Deny) { ' (Deny)' } else { '' }))
}

function Invoke-AreaReceiveConnectors {
    $areaName = 'ReceiveConnectors'
    $sourceConnectors = @(Get-ReceiveConnector -Server $script:SourceShort -ErrorAction Stop)
    $targetConnectors = @(Get-ReceiveConnector -Server $script:TargetShort -ErrorAction Stop)
    foreach ($connector in $sourceConnectors) {
        $label = Convert-ServerName -Value ([string]$connector.Name)
        $counterpart = Get-TargetCounterpart -SourceObject $connector -TargetObjects $targetConnectors
        if ($null -eq $counterpart) {
            Add-Result -Area $areaName -Object $label -Property '(exists)' -SourceValue 'present' -Status SourceOnly -Message 'Connector missing on the target.'
            continue
        }
        Compare-ObjectSettings -Area $areaName -Object $label -SourceObject $connector -TargetObject $counterpart -SetCmdlet 'Set-ReceiveConnector' `
            -Exclude @('TransportRole', 'Usage') -BindingProperties @('Bindings') | Out-Null
        $status = if ([string]$connector.TransportRole -eq [string]$counterpart.TransportRole) { 'Equal' } else { 'Different' }
        Add-Result -Area $areaName -Object $label -Property 'TransportRole' -SourceValue $connector.TransportRole -TargetValue $counterpart.TransportRole -Status $status

        try {
            $sourceAces = @{}
            foreach ($ace in @(Get-ADPermission -Identity ([string]$connector.DistinguishedName) -ErrorAction Stop | Where-Object { -not [bool]$_.IsInherited })) { $sourceAces[(Get-AceKey -Ace $ace)] = Get-AceDescription -Ace $ace }
            $targetAces = @{}
            foreach ($ace in @(Get-ADPermission -Identity ([string]$counterpart.DistinguishedName) -ErrorAction Stop | Where-Object { -not [bool]$_.IsInherited })) { $targetAces[(Get-AceKey -Ace $ace)] = Get-AceDescription -Ace $ace }
            foreach ($key in $sourceAces.Keys) {
                $status = if ($targetAces.ContainsKey($key)) { 'Equal' } else { 'SourceOnly' }
                Add-Result -Area $areaName -Object $label -Property 'ADPermission' -SourceValue $sourceAces[$key] -TargetValue $(if ($status -eq 'Equal') { $sourceAces[$key] } else { '' }) -Status $status
            }
            foreach ($key in $targetAces.Keys) {
                if ($sourceAces.ContainsKey($key)) { continue }
                Add-Result -Area $areaName -Object $label -Property 'ADPermission' -TargetValue $targetAces[$key] -Status TargetOnly
            }
        }
        catch { Add-Result -Area $areaName -Object $label -Property 'ADPermission' -Status Info -Message ('Permissions not readable: {0}' -f $_.Exception.Message) }
    }
    foreach ($connector in $targetConnectors) {
        $found = $false
        foreach ($sourceConnector in $sourceConnectors) { if ((Convert-ServerName -Value ([string]$sourceConnector.Name)) -eq [string]$connector.Name) { $found = $true; break } }
        if (-not $found) { Add-Result -Area $areaName -Object ([string]$connector.Name) -Property '(exists)' -TargetValue 'present' -Status TargetOnly -Message 'Connector exists on the target only.' }
    }
}

