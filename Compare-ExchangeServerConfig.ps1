    }
}

function Invoke-AreaTransportAgents {
    $areaName = 'TransportAgents'
    foreach ($transportService in @('Hub', 'FrontEnd')) {
        $sourceAgents = @(Get-TransportAgent -Server $script:SourceShort -TransportService $transportService -ErrorAction Stop)
        $targetAgents = @(Get-TransportAgent -Server $script:TargetShort -TransportService $transportService -ErrorAction Stop)
        foreach ($agent in $sourceAgents) {
            $name = [string]$agent.Identity
            if (-not $name) { continue }
            $label = '{0}\{1}' -f $transportService, $name
            $counterpart = $targetAgents | Where-Object { [string]$_.Identity -eq $name } | Select-Object -First 1
            if ($null -eq $counterpart) { Add-Result -Area $areaName -Object $label -Property '(exists)' -SourceValue ('enabled {0}, priority {1}' -f $agent.Enabled, $agent.Priority) -Status SourceOnly; continue }
            $status = if ([bool]$agent.Enabled -eq [bool]$counterpart.Enabled) { 'Equal' } else { 'Different' }
            Add-Result -Area $areaName -Object $label -Property 'Enabled' -SourceValue $agent.Enabled -TargetValue $counterpart.Enabled -Status $status
            $status = if ([string]$agent.Priority -eq [string]$counterpart.Priority) { 'Equal' } else { 'Different' }
            Add-Result -Area $areaName -Object $label -Property 'Priority' -SourceValue $agent.Priority -TargetValue $counterpart.Priority -Status $status
        }
        foreach ($agent in $targetAgents) {
            if (-not [string]$agent.Identity) { continue }
            if ($sourceAgents | Where-Object { [string]$_.Identity -eq [string]$agent.Identity }) { continue }
            Add-Result -Area $areaName -Object ('{0}\{1}' -f $transportService, $agent.Identity) -Property '(exists)' -TargetValue ('enabled {0}, priority {1}' -f $agent.Enabled, $agent.Priority) -Status TargetOnly
        }
    }
}

