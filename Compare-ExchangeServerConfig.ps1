#Requires -Version 5.1

<#
.SYNOPSIS
    Compares the client access and transport configuration of two Exchange servers and reports every difference.

.DESCRIPTION
    Read only. Use it after Copy-ExchangeServerConfig.ps1 or after running the script generated by
    Export-ExchangeServerConfigScript.ps1 to prove that the new server matches the source, and later as a drift
    check between the members of the DAG.

    The script reads the same objects on both servers and compares every parameter the matching Set cmdlet
    accepts, so the comparison covers exactly what the two other scripts can set. Each compared property becomes
    a row with a status:

      Equal        same value on both servers (only shown with -ShowEqual)
      Different    both have a value and they differ
      SourceOnly   object or value exists on the source only
      TargetOnly   object or value exists on the target only
      Info         a note that needs no action

    Areas: Certificates, ExchangeServer, ClientAccess, VirtualDirectories, OutlookAnywhere, Transport, PopImap
    (settings plus service startup types), MailboxServer, Malware, EventLogLevels, SettingOverrides,
    ReceiveConnectors (settings plus explicit AD permissions), SendConnectors, TransportAgents, ConfigFiles (hash
    of the commonly customised files over the admin share), Iis (Default Web Site root redirect, SSL flags and
    bindings) and Hybrid.

    Before comparing, the source server name and FQDN inside a value are replaced by those of the target, so
    "Default Frontend EX01" equals "Default Frontend EX02" and the Fqdn of a default connector does not show up as
    a difference. Bindings on a specific IP address are translated with -IpAddressMap. Log and queue paths are
    excluded unless -IncludePaths is given.

    Output: a summary per area and the differences on the console, compare.csv with every row and compare.html
    with a coloured table in the output folder. The script exits with code 0 when no differences were found and
    with the number of differences otherwise, so it can gate a change window.

.PARAMETER SourceServer
    Reference server.

.PARAMETER TargetServer
    Server to compare against the reference.

.PARAMETER Area
    Areas to compare. Defaults to all.

.PARAMETER SkipArea
    Areas to leave out.

.PARAMETER OutputPath
    Folder for compare.csv and compare.html. Defaults to a timestamped folder in the current directory.

.PARAMETER ShowEqual
    Also report properties that are equal, for a full side by side documentation of both servers.

.PARAMETER IpAddressMap
    Hashtable that maps source IP addresses to target IP addresses for connector and protocol bindings.

.PARAMETER IncludePaths
    Also compare log, queue and pickup directory paths.

.PARAMETER NoServerNameSubstitution
    Compare values literally without replacing the source server name by the target server name.

.PARAMETER PassThru
    Also return the result rows as objects on the pipeline.

.EXAMPLE
    .\Compare-ExchangeServerConfig.ps1 -SourceServer EX01 -TargetServer EX02

    Shows the differences and writes compare.csv and compare.html.

.EXAMPLE
    .\Compare-ExchangeServerConfig.ps1 -SourceServer EX01 -TargetServer EX02 -ShowEqual -OutputPath C:\Docs\EX02-asbuilt

    Full side by side documentation of both servers.

.EXAMPLE
    .\Compare-ExchangeServerConfig.ps1 -SourceServer EX01 -TargetServer EX02 -Area ReceiveConnectors, SendConnectors -IpAddressMap @{ '10.0.0.11' = '10.0.0.12' }

    Only the mail flow configuration, with the relay binding translated.

.EXAMPLE
    $rows = .\Compare-ExchangeServerConfig.ps1 -SourceServer EX01 -TargetServer EX02 -PassThru
    $rows | Where-Object Status -ne 'Equal' | Out-GridView

.NOTES
    jentech consulting
    Requirements: Exchange Management Shell with View-Only Organization Management, admin share and WinRM access
    to both servers for the ConfigFiles, PopImap service and Iis areas. Windows PowerShell 5.1.
#>

[CmdletBinding()]
param(
    [Parameter(Mandatory = $true, Position = 0)]
    [ValidateNotNullOrEmpty()]
    [string] $SourceServer,

    [Parameter(Mandatory = $true, Position = 1)]
    [ValidateNotNullOrEmpty()]
    [string] $TargetServer,

    [ValidateSet('Certificates', 'ExchangeServer', 'ClientAccess', 'VirtualDirectories', 'OutlookAnywhere', 'Transport',
                 'PopImap', 'MailboxServer', 'Malware', 'EventLogLevels', 'SettingOverrides', 'ReceiveConnectors',
                 'SendConnectors', 'TransportAgents', 'ConfigFiles', 'Iis', 'Hybrid')]
    [string[]] $Area,

    [ValidateSet('Certificates', 'ExchangeServer', 'ClientAccess', 'VirtualDirectories', 'OutlookAnywhere', 'Transport',
                 'PopImap', 'MailboxServer', 'Malware', 'EventLogLevels', 'SettingOverrides', 'ReceiveConnectors',
                 'SendConnectors', 'TransportAgents', 'ConfigFiles', 'Iis', 'Hybrid')]
    [string[]] $SkipArea = @(),

    [string] $OutputPath,

    [switch] $ShowEqual,

    [hashtable] $IpAddressMap = @{},

    [switch] $IncludePaths,

    [switch] $NoServerNameSubstitution,

    [switch] $PassThru
)

$script:AllAreas = @('Certificates', 'ExchangeServer', 'ClientAccess', 'VirtualDirectories', 'OutlookAnywhere',
                     'Transport', 'PopImap', 'MailboxServer', 'Malware', 'EventLogLevels', 'SettingOverrides',
                     'ReceiveConnectors', 'SendConnectors', 'TransportAgents', 'ConfigFiles', 'Iis', 'Hybrid')

$script:NeverCopy = @('Identity', 'Server', 'DomainController', 'Force', 'Confirm', 'WhatIf', 'AsJob', 'Name')
$script:PathExclusions = @('*Path', '*Location', '*Directory')
if ($IncludePaths) { $script:PathExclusions = @() }

$script:Results = New-Object System.Collections.Generic.List[object]

