function Get-ExchangeInstallShare {
    param($ExchangeServer)
    $dataPath = [string]$ExchangeServer.DataPath
    $installPath = 'C:\Program Files\Microsoft\Exchange Server\V15'
    if ($dataPath) { $installPath = Split-Path -Path $dataPath -Parent }
    return ('\\{0}\{1}' -f $ExchangeServer.Fqdn, ($installPath -replace '^([A-Za-z]):', '$1$$'))
}

function Invoke-AreaConfigFiles {
    $areaName = 'ConfigFiles'
    $sourceRoot = Get-ExchangeInstallShare -ExchangeServer $script:SourceExchangeServer
    $targetRoot = Get-ExchangeInstallShare -ExchangeServer $script:TargetExchangeServer
    if (-not (Test-Path $sourceRoot) -or -not (Test-Path $targetRoot)) {
        Add-Result -Area $areaName -Object 'admin share' -Property '(access)' -SourceValue $sourceRoot -TargetValue $targetRoot -Status Info -Message 'Admin share not reachable, config files not compared.'
        return
    }
    $files = @(
        'Bin\EdgeTransport.exe.config', 'Bin\MSExchangeFrontendTransport.exe.config', 'Bin\MSExchangeDelivery.exe.config',
        'Bin\MSExchangeSubmission.exe.config', 'Bin\MSExchangeMailboxReplication.exe.config', 'Bin\Microsoft.Exchange.Store.Worker.exe.config',
        'Bin\Microsoft.Exchange.Imap4.exe.config', 'Bin\Microsoft.Exchange.Imap4Service.exe.config', 'Bin\Microsoft.Exchange.Pop3.exe.config',
        'Bin\Microsoft.Exchange.Pop3Service.exe.config', 'Bin\Microsoft.Exchange.Directory.TopologyService.exe.config', 'Bin\Microsoft.Exchange.ServiceHost.exe.config',
        'TransportRoles\Shared\agents.config', 'TransportRoles\Shared\fetagents.config',
        'FrontEnd\HttpProxy\SharedWebConfig.config', 'FrontEnd\HttpProxy\web.config', 'FrontEnd\HttpProxy\owa\web.config', 'FrontEnd\HttpProxy\owa\auth\logon.aspx',
        'FrontEnd\HttpProxy\ecp\web.config', 'FrontEnd\HttpProxy\ews\web.config', 'FrontEnd\HttpProxy\rpc\web.config', 'FrontEnd\HttpProxy\mapi\web.config',
        'FrontEnd\HttpProxy\sync\web.config', 'FrontEnd\HttpProxy\oab\web.config', 'FrontEnd\HttpProxy\Autodiscover\web.config', 'FrontEnd\HttpProxy\PowerShell\web.config',
        'ClientAccess\SharedWebConfig.config', 'ClientAccess\Owa\web.config', 'ClientAccess\ecp\web.config', 'ClientAccess\exchweb\ews\web.config',
        'ClientAccess\Sync\web.config', 'ClientAccess\Autodiscover\web.config', 'ClientAccess\mapi\emsmdb\web.config', 'ClientAccess\mapi\nspi\web.config',
        'ClientAccess\PowerShell\web.config', 'ClientAccess\rpc\web.config', 'ClientAccess\OAB\web.config'
    )
    foreach ($relativePath in $files) {
        $sourcePath = Join-Path $sourceRoot $relativePath
        $targetPath = Join-Path $targetRoot $relativePath
        $sourceExists = Test-Path $sourcePath
        $targetExists = Test-Path $targetPath
        if (-not $sourceExists -and -not $targetExists) { continue }
        if (-not $targetExists) { Add-Result -Area $areaName -Object $relativePath -Property 'File' -SourceValue 'present' -Status SourceOnly; continue }
        if (-not $sourceExists) { Add-Result -Area $areaName -Object $relativePath -Property 'File' -TargetValue 'present' -Status TargetOnly; continue }
        $sourceHash = (Get-FileHash -Path $sourcePath -Algorithm SHA256).Hash
        $targetHash = (Get-FileHash -Path $targetPath -Algorithm SHA256).Hash
        $status = if ($sourceHash -eq $targetHash) { 'Equal' } else { 'Different' }
        Add-Result -Area $areaName -Object $relativePath -Property 'SHA256' -SourceValue $sourceHash.Substring(0, 16) -TargetValue $targetHash.Substring(0, 16) -Status $status `
            -Message $(if ($status -eq 'Different') { 'Compare both files, a customisation is likely.' } else { '' })
    }

    # OWA logon customisations and custom themes.
    $authFolder = 'FrontEnd\HttpProxy\owa\auth'
    $sourceAuth = Join-Path $sourceRoot $authFolder
    $targetAuth = Join-Path $targetRoot $authFolder
    if ((Test-Path $sourceAuth) -and (Test-Path $targetAuth)) {
        $targetFiles = @{}
        foreach ($file in @(Get-ChildItem -Path $targetAuth -Recurse -File -ErrorAction SilentlyContinue)) { $targetFiles[$file.FullName.Substring($targetAuth.Length).TrimStart('\')] = $file }
        foreach ($file in @(Get-ChildItem -Path $sourceAuth -Recurse -File -ErrorAction SilentlyContinue)) {
            $relative = $file.FullName.Substring($sourceAuth.Length).TrimStart('\')
            $counterpart = $targetFiles[$relative]
            if ($null -eq $counterpart) { Add-Result -Area $areaName -Object (Join-Path $authFolder $relative) -Property 'File' -SourceValue $file.Length -Status SourceOnly -Message 'OWA logon customisation.'; continue }
            if ($counterpart.Length -ne $file.Length -or ($file.Length -lt 5MB -and (Get-FileHash -Path $file.FullName -Algorithm SHA256).Hash -ne (Get-FileHash -Path $counterpart.FullName -Algorithm SHA256).Hash)) {
                Add-Result -Area $areaName -Object (Join-Path $authFolder $relative) -Property 'File' -SourceValue $file.Length -TargetValue $counterpart.Length -Status Different -Message 'OWA logon customisation.'
            }
        }
    }
    $sourcePrem = Join-Path $sourceRoot 'ClientAccess\Owa\prem'
    $targetPrem = Join-Path $targetRoot 'ClientAccess\Owa\prem'
    if ((Test-Path $sourcePrem) -and (Test-Path $targetPrem)) {
        $sourceThemes = @(Get-ChildItem -Path (Join-Path $sourcePrem '*\resources\themes') -Directory -ErrorAction SilentlyContinue | Select-Object -ExpandProperty Name | Sort-Object -Unique)
        $targetThemes = @(Get-ChildItem -Path (Join-Path $targetPrem '*\resources\themes') -Directory -ErrorAction SilentlyContinue | Select-Object -ExpandProperty Name | Sort-Object -Unique)
        foreach ($theme in $sourceThemes) { if ($targetThemes -notcontains $theme) { Add-Result -Area $areaName -Object ('owa theme {0}' -f $theme) -Property 'Folder' -SourceValue 'present' -Status SourceOnly } }
        foreach ($theme in $targetThemes) { if ($sourceThemes -notcontains $theme) { Add-Result -Area $areaName -Object ('owa theme {0}' -f $theme) -Property 'Folder' -TargetValue 'present' -Status TargetOnly } }
    }
}

$script:IisReadScript = {
    Import-Module WebAdministration -ErrorAction Stop
    $site = 'IIS:\Sites\Default Web Site'
    $redirect = Get-WebConfiguration -Filter 'system.webServer/httpRedirect' -PSPath $site
    $sslRaw = Get-WebConfigurationProperty -Filter 'system.webServer/security/access' -Name sslFlags -PSPath $site
    $sslValue = $sslRaw
    if ($null -ne $sslRaw -and $null -ne $sslRaw.PSObject.Properties['Value']) { $sslValue = $sslRaw.Value }
    [pscustomobject]@{
        RedirectEnabled          = [bool]$redirect.enabled
        RedirectDestination      = [string]$redirect.destination
        RedirectExactDestination = [bool]$redirect.exactDestination
        RedirectChildOnly        = [bool]$redirect.childOnly
        RedirectStatus           = [string]$redirect.httpResponseStatus
        SslFlags                 = [string]$sslValue
        Bindings                 = @(Get-WebBinding -Name 'Default Web Site' | ForEach-Object { '{0} {1}' -f $_.protocol, $_.bindingInformation })
    }
}

function Invoke-AreaIis {
    $areaName = 'Iis'
    try {
        $sourceIis = Invoke-Command -ComputerName $script:SourceFqdn -ScriptBlock $script:IisReadScript -ErrorAction Stop
        $targetIis = Invoke-Command -ComputerName $script:TargetFqdn -ScriptBlock $script:IisReadScript -ErrorAction Stop
    }
    catch { Add-Result -Area $areaName -Object 'Default Web Site' -Property '(read)' -Status Info -Message ('WinRM read failed: {0}' -f $_.Exception.Message); return }
    foreach ($property in @('RedirectEnabled', 'RedirectDestination', 'RedirectExactDestination', 'RedirectChildOnly', 'RedirectStatus', 'SslFlags')) {
        $status = if ([string]$sourceIis.$property -eq [string]$targetIis.$property) { 'Equal' } else { 'Different' }
        Add-Result -Area $areaName -Object 'Default Web Site' -Property $property -SourceValue $sourceIis.$property -TargetValue $targetIis.$property -Status $status
    }
    $sourceBindings = @($sourceIis.Bindings | Sort-Object)
    $targetBindings = @($targetIis.Bindings | Sort-Object)
    $status = if ((Get-CompareKey $sourceBindings) -eq (Get-CompareKey $targetBindings)) { 'Equal' } else { 'Different' }
    Add-Result -Area $areaName -Object 'Default Web Site' -Property 'Bindings' -SourceValue $sourceBindings -TargetValue $targetBindings -Status $status
}

