function Invoke-AreaCertificates {
    $areaName = 'Certificates'
    $sourceCerts = @(Get-ExchangeCertificate -Server $script:SourceShort -ErrorAction Stop)
    $targetCerts = @(Get-ExchangeCertificate -Server $script:TargetShort -ErrorAction Stop)
    $authThumbprints = @()
    try { $authConfig = Get-AuthConfig -ErrorAction Stop; $authThumbprints = @($authConfig.CurrentCertificateThumbprint, $authConfig.NextCertificateThumbprint) | Where-Object { $_ } } catch { }

    foreach ($cert in $sourceCerts) {
        $thumbprint = [string]$cert.Thumbprint
        $label = '{0} ({1})' -f $thumbprint, $cert.Subject
        if ([bool]$cert.IsSelfSigned -and $authThumbprints -notcontains $thumbprint) {
            Add-Result -Area $areaName -Object $label -Property 'Certificate' -SourceValue 'self signed' -Status Info -Message 'Server specific, not compared.'
            continue
        }
        $counterpart = $targetCerts | Where-Object { [string]$_.Thumbprint -eq $thumbprint } | Select-Object -First 1
        if ($null -eq $counterpart) {
            Add-Result -Area $areaName -Object $label -Property 'Certificate' -SourceValue $cert.Services -Status SourceOnly -Message 'Certificate missing on the target.'
            continue
        }
        $sourceServices = @(("$($cert.Services)" -split ',') | ForEach-Object { $_.Trim() } | Where-Object { @('IIS', 'SMTP', 'IMAP', 'POP') -contains $_ })
        $targetServices = @(("$($counterpart.Services)" -split ',') | ForEach-Object { $_.Trim() } | Where-Object { @('IIS', 'SMTP', 'IMAP', 'POP') -contains $_ })
        $status = if ((Get-CompareKey $sourceServices) -eq (Get-CompareKey $targetServices)) { 'Equal' } else { 'Different' }
        Add-Result -Area $areaName -Object $label -Property 'Services' -SourceValue $sourceServices -TargetValue $targetServices -Status $status
    }
    foreach ($cert in $targetCerts) {
        if ([bool]$cert.IsSelfSigned) { continue }
        if ($sourceCerts | Where-Object { [string]$_.Thumbprint -eq [string]$cert.Thumbprint }) { continue }
        Add-Result -Area $areaName -Object ('{0} ({1})' -f $cert.Thumbprint, $cert.Subject) -Property 'Certificate' -TargetValue $cert.Services -Status TargetOnly
    }
}

function Invoke-AreaExchangeServer {
    $source = Get-ExchangeServer -Identity $script:SourceShort -ErrorAction Stop
    $target = Get-ExchangeServer -Identity $script:TargetShort -ErrorAction Stop
    Compare-ObjectSettings -Area 'ExchangeServer' -Object 'ExchangeServer' -SourceObject $source -TargetObject $target -SetCmdlet 'Set-ExchangeServer' -Exclude @('ProductKey', 'Static*') | Out-Null
    $status = if ([string]$source.Edition -eq [string]$target.Edition -and [bool]$source.IsExchangeTrialEdition -eq [bool]$target.IsExchangeTrialEdition) { 'Equal' } else { 'Different' }
    Add-Result -Area 'ExchangeServer' -Object 'ExchangeServer' -Property 'Edition' -SourceValue ('{0} (trial: {1})' -f $source.Edition, $source.IsExchangeTrialEdition) -TargetValue ('{0} (trial: {1})' -f $target.Edition, $target.IsExchangeTrialEdition) -Status $status
    $status = if ([string]$source.AdminDisplayVersion -eq [string]$target.AdminDisplayVersion) { 'Equal' } else { 'Different' }
    Add-Result -Area 'ExchangeServer' -Object 'ExchangeServer' -Property 'AdminDisplayVersion' -SourceValue $source.AdminDisplayVersion -TargetValue $target.AdminDisplayVersion -Status $status
}

function Invoke-AreaClientAccess {
    $source = Get-ClientAccessService -Identity $script:SourceShort -IncludeAlternateServiceAccountCredentialStatus -ErrorAction Stop
    $target = Get-ClientAccessService -Identity $script:TargetShort -IncludeAlternateServiceAccountCredentialStatus -ErrorAction Stop
    Compare-ObjectSettings -Area 'ClientAccess' -Object 'ClientAccessService' -SourceObject $source -TargetObject $target -SetCmdlet 'Set-ClientAccessService' `
        -Exclude @('AlternateServiceAccountCredential', 'RemoveAlternateServiceAccountCredentials', 'CleanUpInvalidAlternateServiceAccountCredentials', 'Array') | Out-Null
    $sourceAsa = $false; $targetAsa = $false
    if ($null -ne $source.AlternateServiceAccountConfiguration -and $null -ne $source.AlternateServiceAccountConfiguration.EffectiveCredentials) { $sourceAsa = (@($source.AlternateServiceAccountConfiguration.EffectiveCredentials).Count -gt 0) }
    if ($null -ne $target.AlternateServiceAccountConfiguration -and $null -ne $target.AlternateServiceAccountConfiguration.EffectiveCredentials) { $targetAsa = (@($target.AlternateServiceAccountConfiguration.EffectiveCredentials).Count -gt 0) }
    $status = if ($sourceAsa -eq $targetAsa) { 'Equal' } elseif ($sourceAsa) { 'SourceOnly' } else { 'TargetOnly' }
    Add-Result -Area 'ClientAccess' -Object 'ClientAccessService' -Property 'AlternateServiceAccount' -SourceValue $(if ($sourceAsa) { 'configured' } else { 'none' }) -TargetValue $(if ($targetAsa) { 'configured' } else { 'none' }) -Status $status
}

